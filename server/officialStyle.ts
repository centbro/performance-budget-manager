/** 기관 양식을 따르는 경우: 구성은 양식이 우선이므로 표기·표현 규칙만 */
export const OFFICIAL_NOTATION_RULES = `[공문서 표기·표현 규칙 — 공문서 작성법 길라잡이(2025) 기준]\n${NOTATION}\n\n${EXPRESSION}`;

export type StyleWarning = { rule: string; found: string; suggestion: string };

const OVERLAP: [RegExp, string][] = [
  [/(\d{1,2})월달/g, "월달 → 월"],
  [/기간\s?동안/g, "기간 동안 → 기간에"],
  [/여러\s?가지\s?종류/g, "여러 가지 종류 → 여러 가지"],
  [/새로\s?신설/g, "새로 신설 → 신설"],
  [/미리\s?예측/g, "미리 예측 → 예측"],
  [/반드시\s?필요/g, "반드시 필요 → 필요"],
  [/월요일\s?날|화요일\s?날|수요일\s?날|목요일\s?날|금요일\s?날/g, "요일 날 → 요일"],
  [/불우\s?이웃/g, "불우 이웃 → 이웃"],
];

/** 공문서 표기 규칙 위반을 찾아 알려준다(자동 수정은 하지 않음). */
export function lintOfficialStyle(text: string, opts: { requireEnd?: boolean } = {}): StyleWarning[] {
  const out: StyleWarning[] = [];
  const push = (rule: string, found: string, suggestion: string) => {
    if (out.length < 30) out.push({ rule, found: found.slice(0, 40), suggestion });
  };

  // 날짜: 일 뒤 마침표 누락, 띄어쓰기 없음
  for (const m of Array.from(text.matchAll(/\d{4}\.\s?\d{1,2}\.\s?\d{1,2}(?![\d.])/g))) {
    push("날짜 표기", m[0], "일 뒤에 마침표를 찍습니다. 예: 2025. 1. 6.");
  }
  for (const m of Array.from(text.matchAll(/\d{4}\.\d{1,2}\.\d{1,2}\./g))) {
    push("날짜 표기", m[0], "마침표 뒤를 한 칸 띄웁니다. 예: 2025. 1. 6.");
  }
  for (const m of Array.from(text.matchAll(/\d{4}년\s?\d{1,2}월\s?\d{1,2}일/g))) {
    push("날짜 표기", m[0], "숫자와 마침표로 씁니다. 예: 2025. 1. 6.");
  }
  // 시간: 오전/오후, 쌍점 양옆 띄움, 24시
  for (const m of Array.from(text.matchAll(/(오전|오후)\s?\d{1,2}(시|:\d{2})/g))) {
    push("시간 표기", m[0], "24시각제로 씁니다. 예: 13:00");
  }
  for (const m of Array.from(text.matchAll(/\d{1,2}\s:\s\d{2}|\d{1,2}:\s\d{2}|\d{1,2}\s:\d{2}/g))) {
    push("시간 표기", m[0], "쌍점 양옆을 띄우지 않습니다. 예: 13:20");
  }
  for (const m of Array.from(text.matchAll(/(?<![\d:])24시(?!간)/g))) {
    push("시간 표기", m[0], "24시 대신 마감 시각(예: 18:00)을 씁니다.");
  }
  // 금액: "금 13,500원" 띄움
  for (const m of Array.from(text.matchAll(/금\s\d[\d,]*\s?원/g))) {
    push("금액 표기", m[0], "금 뒤를 붙입니다. 예: 금13,500원(금일만삼천오백원)");
  }
  // 중첩어 등
  for (const [re, tip] of OVERLAP) {
    for (const m of Array.from(text.matchAll(re))) push("쉬운 표현", m[0], tip);
  }
  // 끝 표시
  if (opts.requireEnd) {
    const last = text.trim().split("\n").filter((l) => l.trim()).pop() ?? "";
    if (!/끝\.\s*$/.test(last)) push("끝 표시", last.slice(-20), "마지막 줄 끝에 두 칸 띄우고 '끝.'을 씁니다.");
  }
  return out;
}
